package io.tiko.coroutines

import io.tiko.UnitOfWork
import io.tiko.runtime.EventChainContext
import io.tiko.runtime.UnitCarrier
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.withContext

/**
 * Runs [block] in a unit of work of its own that lasts across suspension: the `suspend`
 * counterpart of [UnitOfWork.supplyInEventScope] and [UnitOfWork.runInEventScope].
 *
 * ```kotlin
 * post("/orders") {
 *     val receipt = unitOfWork.inEventScope { orders.place(call.receive()) }
 *     call.respond(receipt)
 * }
 * ```
 *
 * - **One unit for the whole block.** The EVENT-scoped instances are the same before and after
 *   every suspension, and on every dispatcher the block moves to with `withContext`.
 * - **The unit closes once**, before this function returns or throws: when the block completes,
 *   when it fails, and when its coroutine is cancelled. Code that still runs after a
 *   cancellation, a `finally` block or a `withContext(NonCancellable)` cleanup, is still in the unit.
 * - **A `launch` or `async` started in the block runs in a unit of work of its own**, with its own
 *   EVENT-scoped instances: a unit of work is single-threaded, and concurrent work is a new unit,
 *   as it is for an asynchronous event handler. Values the child needs are passed to it. Its unit
 *   closes when the child completes.
 *
 * @throws IllegalStateException if a unit of work is already open where this is called, or if
 *   this [UnitOfWork] cannot carry a unit between threads (it is not one a Tiko container hands
 *   out, or its container was generated by a Tiko version before 0.8.0)
 */
public suspend fun <T> UnitOfWork.inEventScope(block: suspend CoroutineScope.() -> T): T {
    val carrier = this as? UnitCarrier
        ?: throw IllegalStateException(
            "${this::class.java.name} cannot carry a unit of work across suspension. Use the UnitOfWork a " +
                "component is handed, or the container Tiko.create(...) returns.",
        )
    check(!carrier.hasUnitOpen()) { UNIT_ALREADY_OPEN }
    return withContext(UnitOfWorkElement(EventChainContext.carriedUnitOpener(carrier)), block)
}
