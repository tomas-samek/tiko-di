package io.tiko.examples.kotlin.outbox

import io.tiko.kafka.serializer.JsonKafkaSerializer
import java.sql.Connection
import java.util.concurrent.Future
import java.util.concurrent.TimeUnit
import javax.sql.DataSource
import org.apache.kafka.clients.producer.ProducerRecord
import org.apache.kafka.clients.producer.RecordMetadata

/** Each example database has one relay. Writers can enqueue while it waits for Kafka. */
class JdbcOutbox(private val database: DataSource) {
    fun publishNext(send: (ProducerRecord<String, ByteArray>) -> Future<RecordMetadata>): Boolean {
        val row = first() ?: return false
        send(ProducerRecord(row.topic, row.key, row.payload)).get(6, TimeUnit.SECONDS)
        // A crash after the acknowledgement and before the delete can produce a duplicate.
        database.connection.use { connection ->
            connection.prepareStatement("DELETE FROM outbox WHERE sequence_no = ?").use { delete ->
                delete.setLong(1, row.sequence)
                delete.executeUpdate()
            }
        }
        return true
    }

    private fun first(): Pending? = database.connection.use { connection ->
        connection.prepareStatement(
            "SELECT sequence_no, topic, message_key, payload FROM outbox ORDER BY sequence_no LIMIT 1",
        ).use { query ->
            query.executeQuery().use { rows ->
                if (rows.next()) Pending(rows.getLong(1), rows.getString(2), rows.getString(3), rows.getBytes(4))
                else null
            }
        }
    }

    private data class Pending(val sequence: Long, val topic: String, val key: String, val payload: ByteArray)

    companion object {
        val SCHEMA = """
            CREATE TABLE IF NOT EXISTS outbox (
                sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                topic VARCHAR(64) NOT NULL,
                message_key VARCHAR(36) NOT NULL,
                payload VARBINARY(8192) NOT NULL
            )
        """.trimIndent()

        private val json = JsonKafkaSerializer()

        /** Call within the transaction that records the business change. */
        fun enqueue(transaction: Connection, topic: String, key: String, payload: Any) {
            transaction.prepareStatement("INSERT INTO outbox (topic, message_key, payload) VALUES (?, ?, ?)")
                .use { insert ->
                    insert.setString(1, topic)
                    insert.setString(2, key)
                    insert.setBytes(3, json.serialize(payload))
                    insert.executeUpdate()
                }
        }
    }
}
