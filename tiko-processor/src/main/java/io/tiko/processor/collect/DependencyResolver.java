package io.tiko.processor.collect;

import io.tiko.annotations.Named;
import io.tiko.annotations.Pick;
import io.tiko.processor.core.model.AnnotationRef;
import io.tiko.processor.core.model.MethodDecl;
import io.tiko.processor.core.model.ParamDecl;
import io.tiko.processor.core.model.TypeRef;
import io.tiko.processor.model.DependencyModel;
import io.tiko.processor.util.ErrorReporter;
import io.tiko.processor.util.TypeUtil;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Turns the parameters of an injection constructor, a static factory or a {@code @Produces}
 * method into {@link DependencyModel}s: {@code Provider<T>} / {@code Picker<T>} unwrapping, the
 * {@code @Named} qualifier and the {@code @Pick} class literal.
 */
public final class DependencyResolver {

    private static final String NAMED = Named.class.getCanonicalName();
    private static final String PICK = Pick.class.getCanonicalName();
    /** The member {@code @Named} and {@code @Pick} carry their qualifier and picked class in. */
    private static final String VALUE = "value";

    private DependencyResolver() {}

    /**
     * The dependencies of {@code executable}'s parameters, in declaration order; empty when a
     * {@code @Pick} class literal did not resolve, which is reported on its parameter.
     */
    public static Optional<List<DependencyModel>> resolve(
            MethodDecl executable, TypeUtil typeUtil, ErrorReporter errors) {
        var dependencies = new ArrayList<DependencyModel>();
        boolean resolved = true;
        for (var parameter : executable.parameters()) {
            var pick = parameter.annotation(PICK);
            if (pick.isPresent() && pick.get().isUnresolved(VALUE)) {
                reportUnresolvedPick(executable, parameter, errors);
                resolved = false;
                continue;
            }
            dependencies.add(dependency(parameter, pick, typeUtil));
        }
        return resolved ? Optional.of(List.copyOf(dependencies)) : Optional.empty();
    }

    private static DependencyModel dependency(ParamDecl parameter, Optional<AnnotationRef> pick, TypeUtil typeUtil) {
        var paramType = parameter.type();
        var typeName = typeUtil.getQualifiedName(paramType);

        // Provider<T> and Picker<T> are wrappers around a base type T. They are
        // mutually exclusive (a parameter can't be both), so detect each and unwrap
        // to the inner T for downstream lookup / codegen.
        boolean isProvider = typeUtil.isProvider(paramType);
        boolean isPicker = !isProvider && typeUtil.isPicker(paramType);
        TypeRef unwrappedType = null;

        if (isProvider) {
            unwrappedType = typeUtil.unwrapProvider(paramType).orElse(null);
        } else if (isPicker) {
            unwrappedType = typeUtil.unwrapPicker(paramType).orElse(null);
        }
        if (unwrappedType != null) {
            typeName = typeUtil.getQualifiedName(unwrappedType);
        }

        var qualifier =
                parameter.annotation(NAMED).map(named -> named.string(VALUE)).orElse("");

        // @Pick's class literal names the implementation to inject; resolve() has already
        // rejected one that does not resolve.
        var pickedType = pick.flatMap(annotation -> annotation.type(VALUE)).orElse(null);
        var pickedTypeName = pickedType == null ? null : typeUtil.getQualifiedName(pickedType);

        return DependencyModel.builder()
                .parameter(parameter)
                .type(paramType)
                .typeName(typeName)
                .qualifier(qualifier)
                .isProvider(isProvider)
                .isPicker(isPicker)
                .unwrappedType(unwrappedType)
                .pickedType(pickedType)
                .pickedTypeName(pickedTypeName)
                .build();
    }

    private static void reportUnresolvedPick(MethodDecl executable, ParamDecl parameter, ErrorReporter errors) {
        var owner =
                executable.owner().map(decl -> decl.className().simpleName()).orElse("");
        var injectionPoint =
                executable.isConstructor() ? "the " + owner + " constructor" : owner + "." + executable.name();
        errors.error(
                parameter.location(),
                "@Pick on parameter '" + parameter.name() + "' of " + injectionPoint
                        + ": the picked class could not be resolved when Tiko collected the injection point,"
                        + " so the implementation to inject cannot be selected",
                "Pick a class compiled in this module or in a dependency; classes generated by another"
                        + " annotation processor are not supported here yet",
                "Check the picked class literal for a typo or a missing import");
    }
}
