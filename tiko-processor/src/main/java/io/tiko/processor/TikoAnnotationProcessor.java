package io.tiko.processor;

import com.google.auto.service.AutoService;
import io.tiko.processor.collect.ComponentCollector;
import io.tiko.processor.core.javac.JavacProcessingEnv;
import java.util.Set;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Generated;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.TypeElement;

/**
 * The javac entry point of the Tiko DI annotation processor.
 *
 * <p>A thin frontend shell: each round it wraps javac in a {@link JavacProcessingEnv} and hands
 * it to the {@link TikoPipeline}, which collects, validates and generates. This class only
 * decides what javac needs decided: which annotations and options to claim, which rounds to hand
 * over, and when to call the pipeline.
 */
@AutoService(Processor.class)
public final class TikoAnnotationProcessor extends AbstractProcessor {

    private TikoPipeline pipeline;

    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        super.init(processingEnv);
        // Active profiles come from the compiler options (e.g. -Atiko.profiles=dev,test)
        this.pipeline = new TikoPipeline(TikoPipeline.parseActiveProfiles(processingEnv.getOptions()));
    }

    /**
     * Claims the compiling JDK's latest source version so users on newer JDKs compiling at
     * a higher {@code --release} don't get javac's "Supported source version ... less than
     * -source" warning (fatal under {@code -Werror}).
     */
    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    /**
     * Every Tiko annotation, not just the entry points, plus {@code @Generated} on the generated
     * sources: javac's {@code -Xlint:processing} reports any annotation no processor supports and
     * claims (returns {@code true} for), which fails {@code -Werror} builds.
     */
    @Override
    public Set<String> getSupportedAnnotationTypes() {
        return Set.of(
                "io.tiko.annotations.*", ComponentCollector.TEST_COMPONENT_FQN, Generated.class.getCanonicalName());
    }

    @Override
    public Set<String> getSupportedOptions() {
        return TikoPipeline.OPTIONS;
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        var env = JavacProcessingEnv.of(processingEnv, roundEnv);
        var tikoAnnotated = TikoPipeline.isEntryPointRound(
                name -> annotations.stream().anyMatch(a -> a.getQualifiedName().contentEquals(name)));

        if (roundEnv.processingOver()) {
            // Generation happens in the round that carries the annotations (#334): creating files
            // here would trigger javac's "created in the last round" warning per generated type
            // and break -Werror. So this is a no-op after generation, and otherwise only warns
            // when Tiko sources never yielded anything to generate.
            var generated = pipeline.finished();
            pipeline.finish(env);
            return generated; // The last round carries no annotations; kept as before
        }

        if (pipeline.finished()) {
            // Tiko sources after generation: the pipeline reports them as too late.
            if (tikoAnnotated) {
                pipeline.process(env);
            }
            return true; // Claim @Generated on the previous round's output (javac claims per type)
        }

        // No entry point this round (e.g. only another processor's @Generated output):
        // nothing for Tiko to collect, and nothing of ours to claim.
        if (!tikoAnnotated) {
            return false;
        }

        pipeline.process(env);

        // Nothing collected yet — a later round may still bring Tiko-annotated sources
        // generated by other processors; defer until something arrives.
        if (!pipeline.collectedAnything()) {
            return true; // Claim the annotations
        }

        // Validate and generate in THIS round (#334): the input set is complete for the
        // overwhelmingly common case (all user sources arrive in the first round), and
        // generating now keeps the final round file-free. Late-arriving Tiko sources are
        // rejected loudly by the pipeline.
        pipeline.finish(env);
        return !pipeline.failed();
    }
}
