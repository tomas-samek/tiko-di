package io.tiko.processor.config;

import io.tiko.processor.core.CodeOutput;
import java.io.IOException;
import java.util.List;

/**
 * Writes {@code META-INF/services/io.tiko.config.ConfigBinder} listing this module's generated
 * binders, which {@code Tiko.create} discovers with {@link java.util.ServiceLoader} (#531). A
 * shaded fat jar's {@code ServicesResourceTransformer} merges every module's entries, where a
 * single-copy manifest would keep only one module's.
 */
public final class ConfigBinderServicesWriter {

    private static final String PATH = "META-INF/services/io.tiko.config.ConfigBinder";
    private static final String GENERATED_PACKAGE = "io.tiko.generated.config";

    private final CodeOutput output;

    public ConfigBinderServicesWriter(CodeOutput output) {
        this.output = output;
    }

    public void write(List<ConfigurationModel> configs) throws IOException {
        if (configs.isEmpty()) return;
        var services = new StringBuilder("# Generated by tiko-processor: this module's @Configuration binders\n");
        for (ConfigurationModel cfg : configs) {
            services.append(GENERATED_PACKAGE)
                    .append('.')
                    .append(cfg.binderSimpleName())
                    .append('\n');
        }
        output.writeResource(PATH, services.toString(), List.of());
    }
}
