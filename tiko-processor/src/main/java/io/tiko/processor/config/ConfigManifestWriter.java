package io.tiko.processor.config;

import io.tiko.processor.core.CodeOutput;
import java.io.IOException;
import java.util.List;

/**
 * Writes META-INF/tiko/configs.txt — one {@code <fqn>=<prefix>} per record — which maps each
 * record to its module's container and feeds tooling. Binders themselves are discovered through
 * the services file {@link ConfigBinderServicesWriter} writes (#531).
 */
public final class ConfigManifestWriter {

    private static final String PATH = "META-INF/tiko/configs.txt";

    private final CodeOutput output;
    private final String moduleRoot;

    /**
     * @param moduleRoot the main container's per-module directory (#537) to write a copy into, or
     *     {@code null} for test-compile output
     */
    public ConfigManifestWriter(CodeOutput output, String moduleRoot) {
        this.output = output;
        this.moduleRoot = moduleRoot;
    }

    public void write(List<ConfigurationModel> configs) throws IOException {
        if (configs.isEmpty()) return;
        writeTo(PATH, configs);
        if (moduleRoot != null) writeTo(moduleRoot + "configs.txt", configs);
    }

    private void writeTo(String path, List<ConfigurationModel> configs) throws IOException {
        var manifest = new StringBuilder("# Auto-generated by tiko-processor — see tiko-config docs\n");
        for (ConfigurationModel cfg : configs) {
            manifest.append(cfg.qualifiedName())
                    .append('=')
                    .append(cfg.prefix())
                    .append('\n');
        }
        output.writeResource(
                path,
                manifest.toString(),
                configs.stream().map(ConfigurationModel::declaration).toList());
    }
}
