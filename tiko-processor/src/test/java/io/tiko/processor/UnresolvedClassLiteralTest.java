package io.tiko.processor;

import static org.assertj.core.api.Assertions.assertThat;

import com.google.testing.compile.CompilationSubject;
import com.google.testing.compile.Compiler;
import com.google.testing.compile.JavaFileObjects;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;
import javax.tools.JavaFileObject;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;

/**
 * A class literal that selects or gates wiring ({@code @Pick}, {@code @Component(expose)},
 * {@code @TestComponent(value)}) and does not resolve when Tiko collects it — here a type another
 * processor generates in the same round — fails the build with a located error instead of being
 * read as absent, which would silently change what gets wired.
 */
class UnresolvedClassLiteralTest {

    private static final JavaFileObject TEST_COMPONENT_ANNO = JavaFileObjects.forSourceLines(
            "io.tiko.test.TestComponent",
            "package io.tiko.test;",
            "import io.tiko.Scope;",
            "import java.lang.annotation.*;",
            "@Retention(RetentionPolicy.SOURCE)",
            "@Target(ElementType.TYPE)",
            "public @interface TestComponent {",
            "    Class<?> value() default Void.class;",
            "    Scope scope() default Scope.SINGLETON;",
            "    String name() default \"\";",
            "}");

    static Stream<Arguments> gates() {
        return Stream.of(
                Arguments.of(
                        "@Pick",
                        JavaFileObjects.forSourceLines(
                                "p.C",
                                "package p;",
                                "import io.tiko.annotations.*;",
                                "@Component",
                                "public class C {",
                                "    @Inject",
                                "    public C(@Pick(Gen.class) Object dep) {}",
                                "}"),
                        6,
                        "@Pick on parameter 'dep' of the C constructor: the picked class could not be resolved",
                        "classes generated by another annotation processor are not supported here yet"),
                Arguments.of(
                        "@Component(expose)",
                        JavaFileObjects.forSourceLines(
                                "p.C",
                                "package p;",
                                "import io.tiko.annotations.*;",
                                "@Component(expose = {Runnable.class, Gen.class})",
                                "public class C implements Runnable {",
                                "    public void run() {}",
                                "}"),
                        4,
                        "@Component(expose = {...}) on C: an exposed type could not be resolved",
                        "types generated by another annotation processor are not supported here yet"),
                Arguments.of(
                        "@TestComponent(value)",
                        JavaFileObjects.forSourceLines(
                                "p.C",
                                "package p;",
                                "import io.tiko.test.TestComponent;",
                                "@TestComponent(value = Gen.class)",
                                "public class C {}"),
                        4,
                        "@TestComponent(value = ...) on p.C: the shadowed type could not be resolved",
                        "types generated by another annotation processor are not supported here yet"));
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("gates")
    void unresolvedGateClassIsReportedNotDropped(
            String gate, JavaFileObject source, int line, String problem, String suggestedFix) {
        var sources = new ArrayList<>(List.of(source));
        if (gate.startsWith("@TestComponent")) {
            sources.add(TEST_COMPONENT_ANNO);
        }

        var compilation = Compiler.javac()
                .withProcessors(new GenGenerator(), new TikoAnnotationProcessor())
                .compile(sources);

        CompilationSubject.assertThat(compilation).failed();
        CompilationSubject.assertThat(compilation)
                .hadErrorContaining(problem)
                .inFile(source)
                .onLine(line);
        CompilationSubject.assertThat(compilation).hadErrorContaining(suggestedFix);
        // The only error is Tiko's: the model was not built, so nothing downstream reports on it.
        assertThat(compilation.errors()).hasSize(1);
        CompilationSubject.assertThat(compilation)
                .hadNoteContaining("Tiko DI: Collected 0 components, 0 factories, 0 event handlers");
    }
}
