package io.tiko.processor;

import static org.assertj.core.api.Assertions.assertThat;

import com.google.testing.compile.CompilationSubject;
import com.google.testing.compile.Compiler;
import com.google.testing.compile.JavaFileObjects;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.io.Writer;
import java.util.Set;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.TypeElement;
import javax.tools.JavaFileObject;
import org.junit.jupiter.api.Test;

/**
 * An {@code @EventTrigger} guard is a gate: a guard class Tiko cannot resolve when it collects the
 * handler (here one another processor generates in the same round) must fail the build with a
 * located error, never compile into a trigger that publishes unconditionally.
 */
class EventTriggerUnresolvedGuardTest {

    @Test
    void guardGeneratedByAnotherProcessorIsReportedNotDropped() {
        JavaFileObject handler = JavaFileObjects.forSourceLines(
                "p.H",
                "package p;",
                "import io.tiko.Scope;",
                "import io.tiko.annotations.*;",
                "@Component(scope = Scope.SINGLETON)",
                "public class H {",
                "    @EventHandler",
                "    @EventTrigger(eventName = \"X\", guard = GenGuard.class)",
                "    public String on(Integer e) { return \"x\"; }",
                "}");

        var compilation = Compiler.javac()
                .withProcessors(new GuardGenerator(), new TikoAnnotationProcessor())
                .compile(handler);

        CompilationSubject.assertThat(compilation).failed();
        CompilationSubject.assertThat(compilation)
                .hadErrorContaining("@EventTrigger(eventName = \"X\") on H.on: a guard class could not be resolved")
                .inFile(handler)
                .onLine(8);
        CompilationSubject.assertThat(compilation)
                .hadErrorContaining("guards generated by another annotation processor are not supported yet");
        // The only error is Tiko's, and the handler never reaches generation: compile-testing
        // exposes no generated files for a failed compile, so the collected-count note shows it.
        assertThat(compilation.errors()).hasSize(1);
        CompilationSubject.assertThat(compilation)
                .hadNoteContaining("Tiko DI: Collected 1 components, 0 factories, 0 event handlers");
    }

    /** Generates the guard class {@code p.GenGuard} in the first round, as a second processor would. */
    private static final class GuardGenerator extends AbstractProcessor {

        private boolean done;

        @Override
        public Set<String> getSupportedAnnotationTypes() {
            return Set.of("*");
        }

        @Override
        public SourceVersion getSupportedSourceVersion() {
            return SourceVersion.latestSupported();
        }

        @Override
        public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
            if (done) {
                return false;
            }
            done = true;
            try (Writer writer =
                    processingEnv.getFiler().createSourceFile("p.GenGuard").openWriter()) {
                writer.write("package p; public class GenGuard implements io.tiko.EventTriggerGuard {"
                        + " public boolean shouldTrigger(Object r, Object e) { return false; } }");
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
            return false;
        }
    }
}
