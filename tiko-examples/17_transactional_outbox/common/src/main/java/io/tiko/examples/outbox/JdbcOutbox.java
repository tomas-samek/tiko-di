package io.tiko.examples.outbox;

import io.tiko.kafka.serializer.JsonKafkaSerializer;
import java.sql.Connection;
import java.sql.SQLException;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;
import java.util.function.Function;
import javax.sql.DataSource;
import org.apache.kafka.clients.producer.ProducerRecord;
import org.apache.kafka.clients.producer.RecordMetadata;

/** Each example database has one relay. Writers can enqueue while it waits for Kafka. */
public final class JdbcOutbox {
    public static final String SCHEMA = """
            CREATE TABLE IF NOT EXISTS outbox (
                sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                topic VARCHAR(64) NOT NULL,
                message_key VARCHAR(36) NOT NULL,
                payload VARBINARY(8192) NOT NULL
            )
            """;

    private static final JsonKafkaSerializer JSON = new JsonKafkaSerializer();
    private final DataSource database;

    public JdbcOutbox(DataSource database) {
        this.database = database;
    }

    /** Call inside the same database transaction that records the business change. */
    public static void enqueue(Connection transaction, String topic, String key, Object payload) throws SQLException {
        try (var insert =
                transaction.prepareStatement("INSERT INTO outbox (topic, message_key, payload) VALUES (?, ?, ?)")) {
            insert.setString(1, topic);
            insert.setString(2, key);
            insert.setBytes(3, JSON.serialize(payload));
            insert.executeUpdate();
        }
    }

    public boolean publishNext(Function<ProducerRecord<String, byte[]>, Future<RecordMetadata>> send)
            throws SQLException, InterruptedException, ExecutionException, TimeoutException {
        Pending pending = first();
        if (pending == null) {
            return false;
        }
        send.apply(new ProducerRecord<>(pending.topic(), pending.key(), pending.payload()))
                .get(6, TimeUnit.SECONDS);
        // An ack followed by a crash before DELETE can produce a duplicate. Consumers must deduplicate.
        try (var connection = database.getConnection();
                var delete = connection.prepareStatement("DELETE FROM outbox WHERE sequence_no = ?")) {
            delete.setLong(1, pending.sequence());
            delete.executeUpdate();
        }
        return true;
    }

    private Pending first() throws SQLException {
        try (var connection = database.getConnection();
                var query = connection.prepareStatement(
                        "SELECT sequence_no, topic, message_key, payload FROM outbox ORDER BY sequence_no LIMIT 1");
                var rows = query.executeQuery()) {
            return rows.next()
                    ? new Pending(rows.getLong(1), rows.getString(2), rows.getString(3), rows.getBytes(4))
                    : null;
        }
    }

    private record Pending(long sequence, String topic, String key, byte[] payload) {}
}
